CREATE TABLE IF NOT EXISTS `bookings` (
  `id` BIGINT AUTO_INCREMENT PRIMARY KEY,
  `booking_number` VARCHAR(50) NOT NULL UNIQUE,
  `date_key` DATE NOT NULL,
  `title` VARCHAR(255) NOT NULL,
  `client_name` VARCHAR(150) NOT NULL,
  `client_phone` VARCHAR(30) NOT NULL,
  `location` VARCHAR(255) NOT NULL,
  `category` ENUM('jathagam', 'temple', 'outdoor') NOT NULL,
  `category_label_tamil` VARCHAR(100) NOT NULL,
  `time_slot` VARCHAR(80) NOT NULL,
  `priest_id` VARCHAR(100) NOT NULL,
  `priest_name` VARCHAR(150) NOT NULL,
  `priest_phone` VARCHAR(30) NULL,
  `status` ENUM('confirmed', 'pending', 'completed', 'cancelled') NOT NULL DEFAULT 'confirmed',
  `total_event_charge` DECIMAL(12, 2) NOT NULL DEFAULT 0,
  `client_advance_amount` DECIMAL(12, 2) NOT NULL DEFAULT 0,
  `client_total_received` DECIMAL(12, 2) NOT NULL DEFAULT 0,
  `priest_total_pay` DECIMAL(12, 2) NOT NULL DEFAULT 0,
  `priest_advance_paid` DECIMAL(12, 2) NOT NULL DEFAULT 0,
  `created_by` BIGINT NULL,
  `created_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  `updated_at` TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX `idx_bookings_date_status` (`date_key`, `status`),
  INDEX `idx_bookings_priest_date` (`priest_id`, `date_key`),
  INDEX `idx_bookings_client_phone` (`client_phone`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;